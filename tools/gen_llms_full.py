#!/usr/bin/env python3
"""Generates llms-full.txt — the whole site's text surface in one fetch.

Run from anywhere: python3 tools/gen_llms_full.py

Agent fetch tools frequently refuse URLs a search has not already returned, which
makes link-following unreliable and a single-file surface the practical one (the
finding that produced llms-full.txt on sgit.ai). This concatenates llms.txt and the
markdown of every page, in reading order. Never edit llms-full.txt by hand.
"""
import sys
from pathlib import Path

ROOT    = Path(__file__).resolve().parents[1]
VERSION = (ROOT / "version").read_text().strip()
HOST    = (ROOT / "CNAME").read_text().strip()
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_pages import PAGES                                      # noqa: E402

ORDER   = ([("llms.txt", "llms.txt — the annotated map"),
            ("index.md", "index.md — the front page")]
           + [(f"{d}/index.md", f"{d}/index.md — {title}") for d, title, _ in PAGES]
           + [("explain/storyboards/index.md", "explain/storyboards/index.md — the storyboards")]
           + [(f"explain/storyboards/{p.parent.name}/index.md", f"explain/storyboards/{p.parent.name}/index.md — a storyboard's script")
              for p in sorted((ROOT / "explain/storyboards").glob("*/index.md"))]
           + [(p.relative_to(ROOT).as_posix(), f"{p.relative_to(ROOT).as_posix()} — admin")
              for p in sorted((ROOT / "admin").rglob("index.md"))]
           + [("articles/index.md", "articles/index.md — the articles")]
           + [(f"articles/{p.stem}.md", f"articles/{p.stem}.md")
              for p in sorted((ROOT / "content/articles").glob("*.md"), reverse=True)])

HEADER = f"""# {HOST} — everything, in one file

Site version: {VERSION}. Generated by tools/gen_llms_full.py — do not edit by hand.

This is /llms.txt, then the front page, then every design page's markdown (the source each
page's HTML is generated from), in reading order. If you can make more than one request,
prefer the individual pages listed in llms.txt; this file is a concatenation of them. The
original design pack is not repeated here: it is verbatim under /project/sources/sharness-brief-pack/.

All content is released under the Creative Commons Attribution 4.0 International licence
(CC BY 4.0).
"""

SEP = "\n\n" + "=" * 78 + "\n== {name}\n" + "=" * 78 + "\n\n"


def main():
    parts = [HEADER]
    for name, title in ORDER:
        parts += [SEP.format(name=title), (ROOT / name).read_text()]
    out = ROOT / "llms-full.txt"
    out.write_text("".join(parts))
    print(f"gen_llms_full: {out.name} — {out.stat().st_size:,} bytes, {len(ORDER)} sections")


if __name__ == "__main__":
    main()
